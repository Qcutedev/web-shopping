const FIELDS = ["name", "sortOrder"] as const;
type Field = (typeof FIELDS)[number];
const COPY = th.admin.categories.fieldErrors;

function notify(message: string) {
  window.dispatchEvent(new CustomEvent(ADMIN_NOTICE_EVENT, { detail: message }));
}

/** Create form (REQ-A-06). The slug is generated by the server. */
export function CategoryCreateForm() {
  const router = useRouter();
  const [name, setName] = useState("");
  const [sortOrder, setSortOrder] = useState("");
  const [errors, setErrors] = useState<FieldErrors<Field>>({});
  const [formMessage, setFormMessage] = useState<string | null>(null);
  const [failure, setFailure] = useState<AdminFailure | null>(null);
  const [pending, setPending] = useState(false);

  async function onSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    if (pending) return;
    setFailure(null);
    setFormMessage(null);
    const result = validateWith<CreateCategoryBody, Field>(
      createCategoryFormSchema,
      createCategoryInput(name, sortOrder),
      FIELDS,
      COPY,
    );
    if (!result.ok) {
      setErrors(result.errors);
      if (result.unplaced) setFormMessage(th.admin.common.formInvalid);
      return;
    }
    setErrors({});
    setPending(true);
    const response = await createCategory(result.body);
    setPending(false);
    if (response.ok) {
      setName("");
      setSortOrder("");
      notify(th.admin.categories.created);
      router.refresh();
      return;
    }
    if (response.code === "VALIDATION_ERROR") {
      const mapped = serverFieldErrors(response.fields, FIELDS, (field, code) =>
        messageForCode(COPY[field], code),
      );
      setErrors(mapped.errors);
      if (mapped.unplaced) setFormMessage(th.admin.common.formInvalid);
      return;
    }
    setFailure(response);
  }

  return (
    <Card as="section" padding="panel" aria-labelledby="category-create-title">
      <CardTitle as="h2" size="panel" id="category-create-title">
        {th.admin.categories.createTitle}
      </CardTitle>
      <form onSubmit={onSubmit} noValidate className="mt-4 flex flex-col gap-4">
        {failure ? (
          <AdminRequestError failure={failure} returnTo={ADMIN_ROUTES.categories} />
        ) : null}
        {formMessage ? <Alert tone="danger">{formMessage}</Alert> : null}
        <div className="grid gap-4 sm:grid-cols-2">
          <InputField
            label={th.admin.categories.name}
            name="name"
            value={name}
            onChange={(event) => setName(event.target.value)}
            errorText={errors.name}
            autoComplete="off"
            required
            disabled={pending}
          />
          <InputField
            label={th.admin.categories.sortOrder}
            name="sortOrder"
            inputMode="numeric"
            value={sortOrder}
            onChange={(event) => setSortOrder(event.target.value)}
            helperText={th.admin.categories.sortOrderHelper}
            errorText={errors.sortOrder}
            autoComplete="off"
            disabled={pending}
          />
        </div>
        <div>
          <Button type="submit" loading={pending}>
            {th.admin.categories.create}
          </Button>
        </div>
      </form>
    </Card>
  );
}

/** Rename and reorder one category in a dialog. Only changed fields are sent. */
function CategoryEdit({ category }: { category: AdminCategoryDto }) {
  const router = useRouter();
  const [open, setOpen] = useState(false);
  const [name, setName] = useState(category.name);
  const [sortOrder, setSortOrder] = useState(String(category.sortOrder));
  const [errors, setErrors] = useState<FieldErrors<Field>>({});
  const [formMessage, setFormMessage] = useState<string | null>(null);
  const [failure, setFailure] = useState<AdminFailure | null>(null);
  const [pending, setPending] = useState(false);

  function openDialog() {
    // Start from what is stored now, not from an earlier unsaved edit.
    setName(category.name);
    setSortOrder(String(category.sortOrder));
    setErrors({});
    setFormMessage(null);
    setFailure(null);
    setOpen(true);
  }

  function close() {
    if (!pending) setOpen(false);
  }

  async function save() {
    if (pending) return;
    setFailure(null);
    setFormMessage(null);
    const changes = categoryChanges(category, { name, sortOrderText: sortOrder });
    if (Object.keys(changes).length === 0) {
      setErrors({});
      setFormMessage(th.admin.categories.noChange);
      return;
    }
    const result = validateWith<UpdateCategoryBody, Field>(
      updateCategoryFormSchema,
      changes,
      FIELDS,
      COPY,
    );
    if (!result.ok) {
      setErrors(result.errors);
      if (result.unplaced) setFormMessage(th.admin.common.formInvalid);
      return;
    }
    setErrors({});
    setPending(true);
    const response = await updateCategory(category.id, result.body);
    setPending(false);
    if (response.ok) {
      setOpen(false);
      notify(th.admin.categories.saved);
      router.refresh();
      return;
    }
    if (response.code === "VALIDATION_ERROR") {
      const mapped = serverFieldErrors(response.fields, FIELDS, (field, code) =>
        messageForCode(COPY[field], code),
      );
      setErrors(mapped.errors);
      if (mapped.unplaced) setFormMessage(th.admin.common.formInvalid);
      return;
    }
    if (response.code === "NOT_FOUND") router.refresh();
    setFailure(response);
  }

  return (
    <>
      <Button type="button" variant="secondary" size="sm" onClick={openDialog}>
        {th.admin.categories.edit}
      </Button>
      <Dialog
        open={open}
        size="md"
        dismissible={!pending}
        closeLabel={th.dialog.close}
        onClose={close}
        title={th.admin.categories.editTitle}
        footer={
          <>
            <Button variant="secondary" disabled={pending} onClick={close}>
              {th.admin.common.cancel}
            </Button>
            <Button loading={pending} onClick={() => void save()}>
              {th.admin.common.save}
            </Button>
          </>
        }
      >
        <form
          onSubmit={(event) => {
            event.preventDefault();
            void save();
          }}
          noValidate
          className="flex flex-col gap-4"
        >
          {failure ? (
            <AdminRequestError failure={failure} returnTo={ADMIN_ROUTES.categories} />
          ) : null}
          {formMessage ? <Alert tone="danger">{formMessage}</Alert> : null}
          <InputField
            label={th.admin.categories.name}
            name="name"
            value={name}
            onChange={(event) => setName(event.target.value)}
            errorText={errors.name}
            autoComplete="off"
            required
            disabled={pending}
          />
          <InputField
            label={th.admin.categories.sortOrder}
            name="sortOrder"
            inputMode="numeric"
            value={sortOrder}
            onChange={(event) => setSortOrder(event.target.value)}
            helperText={th.admin.categories.sortOrderHelperEdit}
            errorText={errors.sortOrder}
            autoComplete="off"
            required
            disabled={pending}
          />
          {/* A form with several fields submits on Enter; the dialog's own button does the same. */}
          <button type="submit" hidden />
        </form>
      </Dialog>
    </>
  );
}

/** The categories, inactive ones included, as a data table with their row actions. */
export function CategoriesTable({ items }: { items: readonly AdminCategoryDto[] }) {
  const columns = th.admin.categories.columns;
  return (
    <Table caption={th.admin.categories.listLabel} captionHidden density="dense" stacked>
      <TableHeader>
        <TableRow interactive={false}>
          <TableHead>{columns.name}</TableHead>
          <TableHead align="end">{columns.sortOrder}</TableHead>
          <TableHead>{columns.status}</TableHead>
          <TableHead>
            <span className="sr-only">{columns.actions}</span>
          </TableHead>
        </TableRow>
      </TableHeader>
      <TableBody>
        {items.map((category) => (
          <TableRow key={category.id}>
            <TableCell rowHeader className="min-w-48">
              <div className={`flex flex-col items-start gap-1 ${USER_NAME_CONTAINER_CLASS}`}>
                <span className="type-label">
                  <UserName>{category.name}</UserName>
                </span>
                <span className="type-small text-foreground-secondary font-normal">
                  <UserName>{category.slug}</UserName>
                </span>
                {category.isSample ? <NoticeLabel>{th.notice.sampleData}</NoticeLabel> : null}
              </div>
            </TableCell>
            <TableCell align="end" label={columns.sortOrder}>
              {category.sortOrder.toLocaleString("th-TH")}
            </TableCell>
            <TableCell label={columns.status}>
              <Badge variant={category.isActive ? "success" : "neutral"}>
                {category.isActive ? th.admin.categories.active : th.admin.categories.inactive}
              </Badge>
            </TableCell>
            <TableCell>
              <div className="flex flex-wrap gap-2">
                <CategoryEdit category={category} />
                <AdminAction
                  spec={{
                    kind: category.isActive ? "category.deactivate" : "category.reactivate",
                    id: category.id,
                  }}
                  returnTo={ADMIN_ROUTES.categories}
                />
                <AdminAction
                  spec={{ kind: "category.delete", id: category.id }}
                  returnTo={ADMIN_ROUTES.categories}
                />
              </div>
            </TableCell>
          </TableRow>
        ))}
      </TableBody>
    </Table>
  );
}
