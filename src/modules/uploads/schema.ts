/**
 * Upload contract (docs/API_CONTRACTS.md section 5.8; REQ-S-05; SECURITY.md TM-17, TM-18,
 * "Upload policy"). The constants and types here are authoritative for `POST /seller/uploads` and
 * `GET /api/files/{key}`.
 *
 * Provisional points (item 8.2-8 of the contract, open for T-041 with security): the storage key
 * pattern, the `Cache-Control` of a served file, and the refusal of a form field other than
 * `file`. Each is one constant below, so a ruling is a one-line change.
 */
import type { ImageRef } from "@/modules/catalog/schema";

/**
 * REQ-S-05: at most 4 MiB per file (4,194,304 bytes). A file of exactly this many bytes is
 * accepted. Lowered from 5 MiB by the owner on 2026-10-29 so that one upload request, file and
 * multipart framing, fits under the request body limit of a Vercel function
 * (PLATFORM_REQUEST_BODY_LIMIT_BYTES; D-051).
 */
export const MAX_UPLOAD_FILE_BYTES = 4_194_304;

/**
 * Room for the multipart framing around the one file: the boundary lines, the part headers, and
 * the closing delimiter. A part's headers may take at most MAX_PART_HEADER_BYTES of it.
 */
export const MULTIPART_OVERHEAD_BYTES = 16_384;

/**
 * The most bytes of a request body the upload reader reads (SR-05 items 3 and 6): 4,210,688.
 * It must stay below PLATFORM_REQUEST_BODY_LIMIT_BYTES (a unit test holds it there), so that a
 * body the reader would accept is never cut off by the platform first.
 */
export const MAX_UPLOAD_BODY_BYTES = MAX_UPLOAD_FILE_BYTES + MULTIPART_OVERHEAD_BYTES;

/**
 * The request body limit of a Vercel function, 4.5 MB, taken as 4,500,000 bytes (the smaller
 * reading of "MB"; D-051, docs/DEPLOYMENT.md "Deploying to Vercel"). Not enforced by this
 * application: it is the ceiling MAX_UPLOAD_BODY_BYTES is checked against.
 */
export const PLATFORM_REQUEST_BODY_LIMIT_BYTES = 4_500_000;

/** The longest header block of one multipart part, in bytes. */
export const MAX_PART_HEADER_BYTES = 8_192;

/** The one form field the endpoint reads (section 5.8: one image per request in `file`). */
export const UPLOAD_FIELD_NAME = "file";

/** The allowed image types (REQ-S-05; DATA_MODEL.md `Upload_contentType_check`). */
export const UPLOAD_CONTENT_TYPES = ["image/jpeg", "image/png", "image/webp"] as const;
export type UploadContentType = (typeof UPLOAD_CONTENT_TYPES)[number];

/** The file name extensions allowed for each type (TM-17: extension allow-list). */
export const UPLOAD_EXTENSIONS: Readonly<Record<UploadContentType, readonly string[]>> = {
  "image/jpeg": ["jpg", "jpeg"],
  "image/png": ["png"],
  "image/webp": ["webp"],
};

/** The longest client file name accepted, in characters. The name is never stored or used. */
export const MAX_CLIENT_FILENAME_LENGTH = 255;

/**
 * **Provisional (item 8.2-8).** A storage key is 32 lower-case hexadecimal digits: 128 random
 * bits from the platform's cryptographic source, generated by the server. The key holds no
 * extension, no separator, and no dot, so it can never name a path outside the storage directory
 * (TM-18). File serving answers 404 for anything that does not match, before any lookup.
 */
export const STORAGE_KEY_PATTERN = /^[0-9a-f]{32}$/;

/** Number of random bytes behind a key (two hexadecimal digits each). */
export const STORAGE_KEY_RANDOM_BYTES = 16;

/**
 * **Provisional (item 8.2-8).** `Cache-Control` of a served file. Nothing is documented as
 * cacheable yet (section 5.8), so the default of every response applies.
 */
export const FILE_CACHE_CONTROL = "no-store";

/**
 * **Provisional.** The field `code` of a 400 for a multipart body whose framing cannot be read
 * (no boundary, a broken delimiter, a part header that is not `Name: value`). Not a schema issue
 * code, like `invalid_json` for a JSON body (section 2.2).
 */
export const INVALID_MULTIPART_FIELD_CODE = "invalid_multipart";

/**
 * Section 5.8 "Lifetime" and DATA_MODEL.md section 8: an upload that no product picture, no store
 * logo, and no order item references becomes an orphan this long after it was created. An orphan
 * is no longer served (404) and the cleanup (cleanup.ts) deletes its row and its bytes (SEC-065).
 * Judged by the database clock.
 */
export const ORPHAN_GRACE_PERIOD_SECONDS = 24 * 60 * 60;

/**
 * **Provisional (SEC-065, owner to rule).** The most uploads that nothing references one store
 * may hold, whatever their age: an orphan past the grace period counts until the cleanup has
 * deleted it, so the disk one store can fill without attaching anything is bounded by this
 * number times MAX_UPLOAD_FILE_BYTES (200 MiB) even when no cleanup runs. One more upload is
 * refused with `409 CONFLICT`, reason UPLOAD_LIMIT_REASON. Attaching an upload, or the cleanup,
 * frees the allowance.
 */
export const MAX_UNATTACHED_UPLOADS_PER_STORE = 50;

/** **Provisional (SEC-065).** `details.reason` of the 409 when the store is at the cap. */
export const UPLOAD_LIMIT_REASON = "UPLOAD_LIMIT";

/** The validated file of an upload request, ready for the service. */
export interface ValidatedImage {
  /** The type the leading bytes show; the declared type and the extension agree with it. */
  contentType: UploadContentType;
  /** The file's bytes, at most MAX_UPLOAD_FILE_BYTES. */
  bytes: Uint8Array;
}

/** Response of `POST /seller/uploads` (section 5.8). TypeScript type of `data`. */
export interface UploadDto extends ImageRef {
  contentType: UploadContentType;
  sizeBytes: number;
}

export function isUploadContentType(value: string): value is UploadContentType {
  return (UPLOAD_CONTENT_TYPES as readonly string[]).includes(value);
}

export function isStorageKey(value: unknown): value is string {
  return typeof value === "string" && STORAGE_KEY_PATTERN.test(value);
}
